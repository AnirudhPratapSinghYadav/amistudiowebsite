// Copies the few platform logos the site uses out of simple-icons (CC0) into a small module.
// Run from the project root:  node scripts/brand_icons.mjs
import { writeFileSync } from 'node:fs';
import * as si from 'simple-icons';

const PICK = {
  spotify: 'siSpotify',
  appleMusic: 'siApplemusic',
  youtube: 'siYoutube',
  youtubeMusic: 'siYoutubemusic',
  tidal: 'siTidal',
  soundcloud: 'siSoundcloud',
  linktree: 'siLinktree',
  whatsapp: 'siWhatsapp',
  instagram: 'siInstagram',
};

const out = Object.fromEntries(Object.entries(PICK).map(([k, name]) => [k, { title: si[name].title, path: si[name].path }]));
writeFileSync(
  new URL('../src/components/brandIcons.js', import.meta.url),
  `// Generated by scripts/brand_icons.mjs from simple-icons ${'(CC0)'}. Do not edit by hand.\nexport const BRAND_ICONS = ${JSON.stringify(out, null, 2)};\n`,
);
console.log('wrote', Object.keys(out).length, 'icons');
